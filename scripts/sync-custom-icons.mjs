// Generates cms/src/admin/custom-icons.mjs from the site's own icon components so the
// Strapi icon picker previews exactly what the website renders.
// Run via `npm run cms:sync-icons`; tests/cms-integration.mjs asserts the output is current.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = join(root, 'src/components/ui/icons');
const outFile = join(root, 'cms/src/admin/custom-icons.mjs');
const roleSrc = join(root, 'src/lib/role-icons.ts');
const roleOut = join(root, 'cms/src/admin/role-icons.mjs');

// Icon component file -> the name editors pick in the CMS. `verified.astro` is the profile
// checkmark, not a selectable brand logo, so it is deliberately absent.
export const CUSTOM_ICON_NAMES = {
  'github.astro': 'Github',
  'linkedin.astro': 'Linkedin',
  'x.astro': 'X',
  'hono.astro': 'HonoIcon',
  'fastapi.astro': 'FastapiIcon',
  'celery.astro': 'Celery',
  'langchain.astro': 'LangChain',
  'langgraph.astro': 'LangGraph',
  'mcp.astro': 'ModelContextProtocol',
  'qdrant.astro': 'Qdrant',
  'chroma.astro': 'Chroma',
  'gemini.astro': 'GoogleGemini',
  'github-actions.astro': 'GitHubActions',
  'numpy.astro': 'NumPy',
  'matplotlib.astro': 'Matplotlib',
  'openai.astro': 'OpenAIIcon',
  'sql.astro': 'SQLIcon',
  'pandas.astro': 'Pandas',
  'cursor.astro': 'Cursor',
  'claude.astro': 'ClaudeIcon',
  'django.astro': 'DjangoIcon',
  'flask.astro': 'FlaskIcon',
  'nextjs.astro': 'NextJsIcon',
  'vercel.astro': 'VercelIcon',
};

export function buildCatalog() {
  const icons = {};
  for (const [file, name] of Object.entries(CUSTOM_ICON_NAMES)) {
    const source = readFileSync(join(iconDir, file), 'utf8');
    const viewBox = source.match(/viewBox="([^"]+)"/)?.[1];
    if (!viewBox) throw new Error(`${file}: no viewBox found`);
    // Keep only the drawing instructions; the wrapper <svg> is re-created by the picker.
    const body = source
      .slice(source.indexOf('>') + 1, source.lastIndexOf('</svg>'))
      .replace(/\{\.\.\.Astro\.props\}/g, '')
      .replace(/<desc>[\s\S]*?<\/desc>/g, '')
      .replace(/\s+/g, ' ')
      .trim();
    if (!body) throw new Error(`${file}: empty icon body`);
    icons[name] = { viewBox, body };
  }
  return icons;
}

export function render(icons) {
  return `// GENERATED by scripts/sync-custom-icons.mjs -- do not edit by hand.
// Source of truth: src/components/ui/icons/*.astro (the components the website renders).
// Regenerate with: npm run cms:sync-icons
export const customIcons = ${JSON.stringify(icons, null, 2)};

export const customIconNames = Object.keys(customIcons);
`;
}

/** Mirrors the website's role-icon list into the admin bundle as plain JS. */
export function renderRoleIcons() {
  const source = readFileSync(roleSrc, 'utf8');
  const names = [...source.matchAll(/"([A-Za-z0-9]+)",/g)].map(m => m[1]);
  if (!names.length) throw new Error('No role icon names found in src/lib/role-icons.ts');
  return `// GENERATED by scripts/sync-custom-icons.mjs -- do not edit by hand.
// Source of truth: src/lib/role-icons.ts
// Regenerate with: npm run cms:sync-icons
export const ROLE_ICON_NAMES = ${JSON.stringify(names, null, 2)};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const unknown = Object.keys(CUSTOM_ICON_NAMES).filter(f => !readdirSync(iconDir).includes(f));
  if (unknown.length) throw new Error(`Missing icon components: ${unknown.join(', ')}`);
  writeFileSync(outFile, render(buildCatalog()));
  writeFileSync(roleOut, renderRoleIcons());
  console.log(`Wrote ${outFile}`);
  console.log(`Wrote ${roleOut}`);
}

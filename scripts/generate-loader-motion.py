"""Build the loader's continuous outline route and corner easing from the local font."""
from collections import defaultdict
from pathlib import Path
import math
import re

from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
font = TTFont(ROOT / "public/fonts/4x4-font.ttf")
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
routes = []
x = 0

for letter in "SC":
    glyph = glyphs[cmap[ord(letter)]]
    recorded = RecordingPen()
    glyph.draw(recorded)
    coords = [point for _, points in recorded.value for point in points]
    left, right = min(p[0] for p in coords), max(p[0] for p in coords)
    top, bottom = max(p[1] for p in coords), min(p[1] for p in coords)
    transformed = RecordingPen()
    glyph.draw(TransformPen(transformed, (1, 0, 0, -1, x - left, top)))
    graph = defaultdict(list)
    contour = []
    edge = 0
    for command, points in transformed.value:
        if command == "moveTo":
            contour = list(points)
        elif command == "lineTo":
            contour.extend(points)
        elif command == "closePath":
            for a, b in zip(contour, contour[1:] + contour[:1]):
                graph[a].append((b, edge))
                graph[b].append((a, edge))
                edge += 1
        else:
            raise ValueError(f"Unexpected font contour: {command}")

    # The pixel contours meet at shared vertices. An Euler circuit joins them
    # there, tracing every edge once without jumping across the glyph's interior.
    start = min(graph)
    stack, route, visited = [start], [], set()
    while stack:
        point = stack[-1]
        choices = [(p, e) for p, e in graph[point] if e not in visited]
        if choices:
            next_point, next_edge = min(choices, key=lambda item: (item[0][1], -item[0][0]))
            visited.add(next_edge)
            stack.append(next_point)
        else:
            route.append(stack.pop())
    assert len(visited) == edge
    routes.append([(p[0] * 100 / 1638, p[1] * 100 / 1638) for p in reversed(route)])
    x += right - left + (top - bottom) / 4

points = [routes[0][0]]
visible = []

def append(route, is_visible):
    points.extend(route)
    visible.extend([is_visible] * len(route))

append(routes[0][1:], True)
# Connect outside the outlines, so the light fades through the space between S/C.
append([(-6, points[-1][1]), (-6, -6), (routes[1][0][0], -6), routes[1][0]], False)
append(routes[1][1:], True)
append([(119, points[-1][1]), (119, 106), (-6, 106), (-6, points[0][1]), points[0]], False)

lengths = [math.dist(a, b) for a, b in zip(points, points[1:])]
# Longer straights reach a higher cruise speed. The stronger S curve spends more
# time near corners and reaches a faster peak in the middle of each straight.
# Allow a gentle handoff between letters instead of rushing across the gap.
weights = [length + 30 if shown else 40 for length, shown in zip(lengths, visible)]
total_length, total_weight = sum(lengths), sum(weights)
distance, time = 0, 0
frames = []
for index in range(len(points)):
    # Ease the whole hidden connection as one move: slow departure, faster
    # crossing, then slow arrival. Intermediate off-outline vertices need no stops.
    include = index == 0 or index == len(lengths) or visible[index - 1] or visible[index]
    if include:
        easing = "cubic-bezier(.6, 0, .4, 1)" if index < len(visible) else "linear"
        frames.append(f"  {time / total_weight * 100:.6f}% {{ stroke-dashoffset: calc(var(--trail) * 4px - {distance / total_length * 1000:.6f}px); animation-timing-function: {easing}; }}")
    if index < len(lengths):
        distance += lengths[index]
        time += weights[index]

css = "/* Generated by scripts/generate-loader-motion.py from the local 4x4 font. */\n@keyframes loader-outline-trace {\n" + "\n".join(frames) + "\n}\n"
(ROOT / "src/styles/loader-trace.css").write_text(css)
fmt = lambda p: ",".join(f"{v:.3f}".rstrip("0").rstrip(".") for v in p)
path = "M" + "L".join(map(fmt, points))
asset = ROOT / "src/assets/sc-loader.svg"
svg = asset.read_text()
svg = re.sub(r'(<path id="sc-loader-route" d=")[^"]+', lambda match: match[1] + path, svg)
svg = re.sub(r'(stroke="white" stroke-width=")[^"]+', r'\g<1>2.142857', svg)
# Nested strokes all end at the same head. Their alpha accumulates into a
# tapered tail, avoiding the rounded beads of adjacent short dash segments.
# One filtered group supplies both the soft core and glow, so each stroke only
# needs one animation rather than separate core/glow copies.
count = 40
trail = []
previous = 0
for index in reversed(range(count)):
    offset = 68 * index / (count - 1)
    brightness = (1 - index / count) ** 2
    opacity = (brightness - previous) / (1 - previous)
    previous = brightness
    trail.append(f'<use href="#sc-loader-route" class="loader-beam" style="--trail:{offset / 4:.6f};--beam-length:{4.1 + offset:.6f};--beam-gap:{995.9 - offset:.6f};opacity:{opacity:.6f}" />')
filter_svg = '''<filter id="sc-loader-glow" x="-10%" y="-20%" width="120%" height="140%" color-interpolation-filters="sRGB">
      <feGaussianBlur in="SourceGraphic" stdDeviation=".65" result="core" />
      <feGaussianBlur in="SourceGraphic" stdDeviation="2.4" result="glow" />
      <feComponentTransfer in="glow" result="soft-glow"><feFuncA type="linear" slope=".7" /></feComponentTransfer>
      <feMerge><feMergeNode in="soft-glow" /><feMergeNode in="core" /></feMerge>
    </filter>'''
svg = re.sub(r'<filter id="sc-loader-glow".*?</filter>', filter_svg, svg, flags=re.S)
svg = svg[:svg.index('  <use href="#sc-loader-outline" class="loader-outline"')] + '''  <use href="#sc-loader-outline" class="loader-outline" />
  <g class="loader-trail" filter="url(#sc-loader-glow)">
    <g mask="url(#sc-loader-mask)">''' + "\n".join(trail) + '''</g>
  </g>
</svg>
'''
asset.write_text(svg)
print(f"Generated continuous SC outline motion: {len(lengths)} edges, {len(frames)} easing keyframes.")

import assert from 'node:assert/strict';
import { getBuildInfo, githubRepository } from '../src/lib/build-info.ts';
const settings = { repositoryUrl: 'https://github.com/s4meer-git/Portfolio?utm_source=test', repositoryBranch: 'release/site' };
const sha = 'a'.repeat(40);
const calls = [];
const fetcher = async (url, options) => {
  calls.push({url, options});
  return Response.json({sha, commit:{committer:{date:'2026-09-22T09:00:00Z'}}});
};
assert.equal(githubRepository(settings.repositoryUrl),'https://github.com/s4meer-git/Portfolio');
assert.equal(githubRepository('https://github.com/s4meer-git/Portfolio.git'),'https://github.com/s4meer-git/Portfolio');
assert.equal(githubRepository('https://github.com.evil.test/a/b'),undefined);
assert.equal(githubRepository('https://localhost/a/b'),undefined);
const local = await getBuildInfo(settings,{local:true,fetcher});
assert.equal(local.label,'Developer build');
assert.equal(calls.length,0,'local does not fetch GitHub');
const latest = await getBuildInfo(settings,{local:false,env:{},fetcher});
assert.equal(latest.source,'repository');
assert.equal(latest.label,'aaaaaaa');
assert.equal(latest.date,'2026-09-22');
assert.match(calls[0].url,/release%2Fsite$/);
const deployed = await getBuildInfo(settings,{local:false,env:{BUILD_COMMIT_SHA:sha},fetcher});
assert.equal(deployed.source,'deployment');
assert.ok(calls[1].url.endsWith(sha),'deployment SHA wins over configured branch');
const failure = async () => new Response('',{status:403});
assert.equal((await getBuildInfo(settings,{local:false,env:{},fetcher:failure})).source,'unavailable');
assert.equal((await getBuildInfo(settings,{local:false,env:{BUILD_COMMIT_SHA:sha},fetcher:failure})).label,'aaaaaaa');
assert.equal((await getBuildInfo({},{local:false,env:{},fetcher})).source,'unavailable');
console.log('PASS: local build, configured repository/ref, deployed SHA, date, GitHub failures, invalid URLs.');
